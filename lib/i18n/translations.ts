export const translations: Record<Locale, Record<Key, string>> = { en, he };

export function translate(locale: Locale, key: Key, vars?: Record<string, string | number>): string {
  let str = translations[locale]?.[key] ?? translations[DEFAULT_LOCALE][key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      str = str.replaceAll(`{{${k}}}`, String(v));
    }
  }
  return str;
}
